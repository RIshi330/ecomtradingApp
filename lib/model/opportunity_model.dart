class OpportunityModel {
  final String title;
  final String reference;
  final String location;
  final String type;
  final String category;
  final String status;
  final int views;
  final int responses;
  final String date;

  OpportunityModel({
    required this.title,
    required this.reference,
    required this.location,
    required this.type,
    required this.category,
    required this.status,
    required this.views,
    required this.responses,
    required this.date,
  });
}
